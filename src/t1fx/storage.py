"""Content-addressed JSON artifacts, published atomically and verified on read."""

import hashlib
import json
import os
import re
import shutil
import tempfile
from pathlib import Path


def canonical_bytes(value) -> bytes:
    return (json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + "\n").encode()


def digest(value) -> str:
    return hashlib.sha256(canonical_bytes(value)).hexdigest()


class ArtifactError(ValueError):
    pass


class RunStore:
    def __init__(self, root: Path):
        self.root = root

    def _directory(self, run_id: str) -> Path:
        if re.fullmatch(r"run-[0-9a-f]{20}", run_id) is None:
            raise ArtifactError("Invalid run ID")
        return self.root / "runs" / run_id

    def publish(self, artifacts: dict[str, object], metadata: dict) -> str:
        if set(metadata) & {"schema_version", "run_id", "status", "files"}:
            raise ArtifactError("Metadata cannot override manifest identity fields")
        if any(re.fullmatch(r"[a-z_]+\.json", name) is None for name in artifacts):
            raise ArtifactError("Invalid artifact name")
        if "manifest.json" in artifacts:
            raise ArtifactError("Manifest is generated by the store")
        checksums = {name: digest(value) for name, value in artifacts.items()}
        run_id = f"run-{digest({'files': checksums, 'metadata': metadata})[:20]}"
        target = self._directory(run_id)
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            self.validate(run_id)
            return run_id
        temporary = Path(tempfile.mkdtemp(prefix=".staging-", dir=target.parent))
        try:
            for name, value in artifacts.items():
                (temporary/name).write_bytes(canonical_bytes(value))
            manifest = {"schema_version": "1.0", "run_id": run_id, "status": "SUCCEEDED",
                        "files": checksums, **metadata}
            (temporary/"manifest.json").write_bytes(canonical_bytes(manifest))
            try:
                os.rename(temporary, target)
            except OSError:
                if not target.exists():
                    raise
                self.validate(run_id)
        finally:
            if temporary.exists():
                shutil.rmtree(temporary)
        return run_id

    def manifest(self, run_id: str) -> dict:
        path = self._directory(run_id)/"manifest.json"
        if not path.is_file():
            raise FileNotFoundError(run_id)
        try:
            manifest = json.loads(path.read_text())
        except (ValueError, OSError) as exc:
            raise ArtifactError("Unreadable run manifest") from exc
        if manifest.get("run_id") != run_id or manifest.get("status") != "SUCCEEDED":
            raise ArtifactError("Invalid or incomplete run manifest")
        metadata = {key: value for key, value in manifest.items()
                    if key not in {"schema_version", "run_id", "status", "files"}}
        expected_id = f"run-{digest({'files': manifest.get('files'), 'metadata': metadata})[:20]}"
        if expected_id != run_id:
            raise ArtifactError("Manifest identity does not match its contents")
        return manifest

    def read(self, run_id: str, name: str):
        manifest = self.manifest(run_id)
        if name not in manifest["files"] or re.fullmatch(r"[a-z_]+\.json", name) is None:
            raise ArtifactError("Unknown artifact")
        path = self._directory(run_id)/name
        if not path.is_file():
            raise ArtifactError(f"Missing artifact: {name}")
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != manifest["files"][name]:
            raise ArtifactError(f"Artifact checksum mismatch: {name}")
        return json.loads(raw)

    def validate(self, run_id: str) -> dict:
        manifest = self.manifest(run_id)
        for name in manifest["files"]:
            self.read(run_id, name)
        return manifest

    def list_runs(self) -> list[dict]:
        runs = []
        for path in sorted((self.root/"runs").glob("run-*/manifest.json")):
            runs.append(self.manifest(path.parent.name))
        return runs
